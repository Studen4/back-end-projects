    <h2>11. Кількість «щасливих» квитків (сума перших трьох цифр = сума останніх трьох)</h2>
    <?php
        $count = 0;
        for ($i = 0; $i <= 999999; $i++) {
            $s = str_pad($i, 6, "0", STR_PAD_LEFT);
            $left = $s[0] + $s[1] + $s[2];
            $right = $s[3] + $s[4] + $s[5];
            if ($left == $right) {
                $count++;
            }
        }
        echo "Кількість щасливих квитків: " . $count;
    ?>

